// Generate src/generated/protocol-types.ts from schema/protocol.schema.json.
// Run with the package gen script; build also invokes it automatically.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../schema/protocol.schema.json");
const outPath = resolve(here, "../src/generated/protocol-types.ts");

const schema = JSON.parse(await readFile(schemaPath, "utf8"));

const ts = await compile(schema, schema.title ?? "OctoHarnessProtocolSchema", {
  // Generate every definition, including definitions not referenced by the root.
  unreachableDefinitions: true,
  // Add an index signature only when the schema explicitly allows additional properties.
  additionalProperties: false,
  bannerComment: [
    "/* eslint-disable */",
    "/**",
    " * Generated by scripts/gen-types.mjs from schema/protocol.schema.json.",
    " * Do not edit directly; update the schema and run `pnpm gen`.",
    " */"
  ].join("\n"),
  style: { singleQuote: false }
});

await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, ts, "utf8");
console.error(`generated ${outPath}`);
